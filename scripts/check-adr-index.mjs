#!/usr/bin/env node
/**
 * check-adr-index.mjs — V13-OPS (v12.9.0)
 *
 * Ensures that docs/adr/README.md is up-to-date with the ADR source files.
 * Runs `generate-adr-index.mjs` in dry-run mode (writing to a temp buffer),
 * then diffs the result against the checked-in file.
 *
 * Exit 1 if stale — devs must run `npm run adr:index` to regenerate.
 *
 * Usage:
 *   node scripts/check-adr-index.mjs
 */

import { readFileSync, readdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dir, "..");
const ADR_DIR = join(ROOT, "docs", "adr");
const OUTPUT = join(ADR_DIR, "README.md");

// ── Pure helpers (exported-by-convention for unit tests) ─────────────────────

/**
 * Parse metadata from an ADR file's text content.
 * Handles bold-inline, plain table, and bold table cell formats.
 */
export function parseAdrContent(fileText, fileName) {
  const lines = fileText.split("\n");

  // Title: first # heading, strip "ADR-NNN: " or "ADR-NNN — " prefix
  const titleLine = lines.find((l) => l.startsWith("# "));
  const title = titleLine
    ? titleLine.replace(/^#\s*ADR-\d+[:\s—-]+\s*/, "").trim()
    : basename(fileName, ".md");

  // Date
  const datePatterns = [
    /^\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})/,
    /^\|\s*\*?\*?Date\*?\*?\s*\|\s*(\d{4}-\d{2}-\d{2})/,
  ];
  let date = "—";
  for (const l of lines) {
    for (const pat of datePatterns) {
      const m = l.match(pat);
      if (m) {
        date = m[1];
        break;
      }
    }
    if (date !== "—") break;
  }

  // Status
  const statusPatterns = [/^\*\*Status:\*\*\s*(.+)/, /^\|\s*\*?\*?Status\*?\*?\s*\|\s*([^|]+)\|/];
  let status = "—";
  for (const l of lines) {
    for (const pat of statusPatterns) {
      const m = l.match(pat);
      if (m) {
        status = m[1].trim();
        break;
      }
    }
    if (status !== "—") break;
  }

  return { file: basename(fileName), title, date, status };
}

/**
 * Pad a string to a minimum width.
 */
export function pad(str, width) {
  return str + " ".repeat(Math.max(0, width - str.length));
}

/**
 * Build the README.md content from a list of parsed ADR metadata objects.
 */
export function buildAdrIndex(adrs) {
  const linkWidth = Math.max(
    ...adrs.map((a) => `[${a.file.replace(".md", "")}](${a.file})`.length),
    3,
  );
  const titleWidth = Math.max(...adrs.map((a) => a.title.length), 5);
  const dateWidth = Math.max(...adrs.map((a) => a.date.length), 4);
  const statusWidth = Math.max(...adrs.map((a) => a.status.length), 6);

  const header = `| ${pad("ADR", linkWidth)} | ${pad("Title", titleWidth)} | ${pad("Date", dateWidth)} | ${pad("Status", statusWidth)} |`;
  const sep = `| ${"-".repeat(linkWidth)} | ${"-".repeat(titleWidth)} | ${"-".repeat(dateWidth)} | ${"-".repeat(statusWidth)} |`;
  const rows = adrs.map((a) => {
    const adrNum = a.file.replace(/^(ADR-\d+).*\.md$/, "$1");
    const link = `[${adrNum}](${a.file})`;
    return `| ${pad(link, linkWidth)} | ${pad(a.title, titleWidth)} | ${pad(a.date, dateWidth)} | ${pad(a.status, statusWidth)} |`;
  });

  return [
    "# ADR Index",
    "",
    "> Architectural Decision Records for FamilyDashBoard.",
    "> Auto-generated by `scripts/generate-adr-index.mjs` — do not edit manually.",
    "",
    header,
    sep,
    ...rows,
    "",
  ].join("\n");
}

// ── Main runner ───────────────────────────────────────────────────────────────

const isMain =
  process.argv[1] === fileURLToPath(import.meta.url) ||
  process.argv[1]?.endsWith("check-adr-index.mjs");

if (isMain) {
  const files = readdirSync(ADR_DIR)
    .filter((f) => /^ADR-\d{3}-.+\.md$/.test(f))
    .sort();

  if (files.length === 0) {
    console.error("❌  No ADR files found in docs/adr/");
    process.exit(1);
  }

  const adrs = files.map((f) => {
    const text = readFileSync(join(ADR_DIR, f), "utf8");
    return parseAdrContent(text, f);
  });

  const generated = buildAdrIndex(adrs);
  const current = readFileSync(OUTPUT, "utf8");

  if (generated !== current) {
    console.error("❌  docs/adr/README.md is stale — ADR source files have changed.");
    console.error("   Run: npm run adr:index");
    console.error(`   ADRs scanned: ${files.length} — ${files.join(", ")}`);
    process.exit(1);
  }

  console.log(`✅  docs/adr/README.md is up-to-date (${files.length} ADRs)`);
}
