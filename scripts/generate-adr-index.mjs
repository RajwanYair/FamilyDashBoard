#!/usr/bin/env node
/**
 * generate-adr-index.mjs — Auto-generate docs/adr/README.md from ADR files.
 *
 * Scans docs/adr/ADR-*.md, extracts title / date / status from inline
 * markdown fields (**Date:**, **Status:**), and writes a sorted table.
 *
 * Usage:
 *   node scripts/generate-adr-index.mjs
 *   npm run adr:index
 *
 * V13-S22
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dir = fileURLToPath(new URL(".", import.meta.url));
const ADR_DIR = join(__dir, "..", "docs", "adr");
const OUTPUT = join(ADR_DIR, "README.md");

/** Parse a single ADR file and return its metadata. */
function parseAdr(filePath) {
  const content = readFileSync(filePath, "utf8");
  const lines = content.split("\n");

  // Title: strip "# ADR-NNN: " or "# ADR-NNN — " prefix from first heading
  const titleLine = lines.find((l) => l.startsWith("# "));
  const title = titleLine
    ? titleLine.replace(/^#\s*ADR-\d+[:\s—-]+\s*/, "").trim()
    : basename(filePath, ".md");

  // Date extraction — handles 3 formats:
  //   1. **Date:** 2026-04-23          (bold inline)
  //   2. | Date       | 2026-04-23 |   (plain table cell)
  //   3. | **Date**   | 2026-04-23 |   (bold table cell)
  const datePatterns = [
    /^\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})/,
    /^\|\s*\*?\*?Date\*?\*?\s*\|\s*(\d{4}-\d{2}-\d{2})/,
  ];
  let date = "—";
  for (const l of lines) {
    for (const pat of datePatterns) {
      const m = l.match(pat);
      if (m) {
        date = m[1];
        break;
      }
    }
    if (date !== "—") break;
  }

  // Status extraction — handles 3 formats:
  //   1. **Status:** Accepted
  //   2. | Status     | Accepted |
  //   3. | **Status** | Accepted |
  const statusPatterns = [/^\*\*Status:\*\*\s*(.+)/, /^\|\s*\*?\*?Status\*?\*?\s*\|\s*([^|]+)\|/];
  let status = "—";
  for (const l of lines) {
    for (const pat of statusPatterns) {
      const m = l.match(pat);
      if (m) {
        status = m[1].trim();
        break;
      }
    }
    if (status !== "—") break;
  }

  return { file: basename(filePath), title, date, status };
}

/** Pad a string with spaces to a minimum width. */
function pad(str, width) {
  return str + " ".repeat(Math.max(0, width - str.length));
}

// ── Collect ADR files ─────────────────────────────────────────────────────────

const files = readdirSync(ADR_DIR)
  .filter((f) => /^ADR-\d{3}-.+\.md$/.test(f))
  .sort();

if (files.length === 0) {
  console.error("No ADR files found in", ADR_DIR);
  process.exit(1);
}

const adrs = files.map((f) => parseAdr(join(ADR_DIR, f)));

// ── Compute column widths ─────────────────────────────────────────────────────

const linkWidth = Math.max(...adrs.map((a) => `[${a.file.replace(".md", "")}](${a.file})`.length), 6);
const titleWidth = Math.max(...adrs.map((a) => a.title.length), 5);
const dateWidth = Math.max(...adrs.map((a) => a.date.length), 4);
const statusWidth = Math.max(...adrs.map((a) => a.status.length), 6);

// ── Build table ───────────────────────────────────────────────────────────────

const header = `| ${pad("ADR", linkWidth)} | ${pad("Title", titleWidth)} | ${pad("Date", dateWidth)} | ${pad("Status", statusWidth)} |`;
const sep = `| ${"-".repeat(linkWidth)} | ${"-".repeat(titleWidth)} | ${"-".repeat(dateWidth)} | ${"-".repeat(statusWidth)} |`;
const rows = adrs.map((a) => {
  const adrNum = a.file.replace(/^(ADR-\d+).*\.md$/, "$1");
  const link = `[${adrNum}](${a.file})`;
  return `| ${pad(link, linkWidth)} | ${pad(a.title, titleWidth)} | ${pad(a.date, dateWidth)} | ${pad(a.status, statusWidth)} |`;
});

const content = [
  "# ADR Index",
  "",
  "> Architectural Decision Records for FamilyDashBoard.",
  "> Auto-generated by `scripts/generate-adr-index.mjs` — do not edit manually.",
  "",
  header,
  sep,
  ...rows,
  "",
].join("\n");

// ── Write output ──────────────────────────────────────────────────────────────

writeFileSync(OUTPUT, content, "utf8");
console.log(`✓ Wrote ${adrs.length} ADR entries to docs/adr/README.md`);
